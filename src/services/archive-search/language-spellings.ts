/**
 * One row per language, its spellings in the order they are sent: the ISO 639-2/B code, the
 * 639-2/T code where it differs, the ISO 639-1 code, the English names, then any discontinued
 * MARC codes. Advanced Search stores a language under any of these (`eng` 25.6M texts,
 * `English` 12.5M, `en` 92K; `scr` 14,781, `Croatian` 3,719, `hrv` 958), so a filter on one
 * spelling misses most of the records.
 *
 * Built from two Library of Congress lists, fetched 2026-11-12:
 * - ISO 639-2 (https://www.loc.gov/standards/iso639-2/ISO-639-2_utf-8.txt), every row except
 *   the `qaa-qtz` local-use range. Each `; `-separated English name is a spelling, without a
 *   trailing parenthetical ("Occitan (post 1500)" → "Occitan"; the field is tokenized, so the
 *   shorter phrase also matches the qualified form). An inverted name is also given uninverted
 *   ("English, Old" → "Old English"), except the "Creoles and pidgins, …" rows. `gre` adds
 *   "Greek", the name the Archive stores for it.
 * - The MARC Code List for Languages (https://www.loc.gov/standards/codelists/languages.xml):
 *   its 31 obsolete codes, each in the row of the current code that took over its name or
 *   lists it as a former name (`scr` → Croatian, `mol` → Romanian), or in a row of its own with
 *   its MARC name where none did (`ajm`, `esk`).
 * A name spelled like its row's code (`ewe`, "Ewe") is listed once, the field being
 * case-insensitive. A spelling two rows share is left out of both, since it names neither
 * language reliably: "ga" (the 639-1 code of Irish and the name of Ga) and "Tonga" (both `ton`
 * and `tog`).
 */
