/**
 * ISO 639-1 codes that are also English words. Inside the tokenized `language` field they also
 * match free text (`no` matches "No linguistic content"), so one joins its language's spellings
 * only when it is the value sent.
 */
const ENGLISH_WORD_CODES = new Set([
  'am',
  'an',
  'as',
  'be',
  'he',
  'hi',
  'is',
  'it',
  'my',
  'no',
  'or',
  'so',
  'to',
]);

/** Each spelling, lowercased, mapped to its language's row. */
const ROW_BY_SPELLING = new Map(
  LANGUAGES.flatMap((row) => row.map((spelling) => [spelling.toLowerCase(), row] as const)),
);

/**
 * The spellings a `language` filter value is matched against: the value as sent, then — when it
 * equals a spelling in the table, case-insensitively — every other spelling of that language. A
 * value outside the table is matched alone.
 */
export function languageSpellings(value: string): string[] {
  const key = value.toLowerCase();
  const row = ROW_BY_SPELLING.get(key);
  if (!row) return [value];
  return [
    value,
    ...row.filter(
      (spelling) => spelling.toLowerCase() !== key && !ENGLISH_WORD_CODES.has(spelling),
    ),
  ];
}
